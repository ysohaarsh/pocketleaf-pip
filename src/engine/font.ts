/** Throws when any glyph is not exactly `w`×`h` of '#' and '.'. */
export function validateGlyphs(
  glyphs: Readonly<Record<string, readonly string[]>>,
  w: number,
  h: number,
): void {
  for (const [ch, rows] of Object.entries(glyphs)) {
    if (ch.length !== 1) throw new Error(`font: key "${ch}" must be a single character`);
    if (rows.length !== h) throw new Error(`font: '${ch}' has ${rows.length} rows, expected ${h}`);
    rows.forEach((row, y) => {
      if (row.length !== w || !/^[#.]+$/.test(row)) {
        throw new Error(`font: '${ch}' row ${y} "${row}" must be ${w} chars of '#' or '.'`);
      }
    });
  }
}

